// web/static/lib/objects/motion-css.js
// The motion tokens as styles.css carries them, written from motion.js:
// scripts/motion-tokens.mjs prints this (or, with --write, puts it in
// styles.css between its two marker comments), and motion-tokens.test.js
// fails when what styles.css has is not exactly it.
//
// Dev and tests only: no page imports it, so it is not in sw.js's SHELL.
import { T, EASES, SPRINGS, springEasing } from './motion.js';
import { bezier } from '../scene/choreo.js';

/** The markers the generated block sits between in styles.css. */
export const BEGIN = '/* motion tokens: generated by scripts/motion-tokens.mjs from lib/objects/motion.js; edit those, not this */';
export const END = '/* motion tokens: end */';

/** The springs CSS plays, by name: the needle is stepped on the ticker, never by CSS. */
export const CSS_SPRINGS = ['snap', 'lid', 'carry'];

/** What less motion zeroes: everything that travels. A fade (touch, exit) stays: it says what changed without moving it. */
export const TRAVEL = ['release', 'move', 'sheet', 'room', 'flight'];

const num = (v) => String(Math.round(v * 1000) / 1000).replace(/^(-?)0\./, '$1.');
const cubic = (p) => `cubic-bezier(${p.map(num).join(',')})`;

/** curveOf is a spring's motion from rest to 1 as a function of progress (0..1) over its CSS duration. */
export function curveOf(s) {
  const pts = /linear\(([^)]*)\)/.exec(springEasing(s).easing)[1].split(',').map(Number);
  const n = pts.length - 1;
  return (p) => {
    if (p <= 0) return 0;
    if (p >= 1) return 1;
    const i = Math.min(n - 1, Math.floor(p * n));
    return pts[i] + (pts[i + 1] - pts[i]) * (p * n - i);
  };
}

/** gap is the most a cubic-bézier strays from a curve, over a hundred points. */
export function gap(points, curve) {
  const f = bezier(...points);
  let worst = 0;
  for (let i = 1; i < 100; i++) worst = Math.max(worst, Math.abs(f(i / 100) - curve(i / 100)));
  return worst;
}

/**
 * fallbackOf is the cubic-bézier nearest a spring's curve: what a browser
 * without linear() plays instead. A pattern search from --ease-out, to two
 * decimals, so the same spring always gives the same answer.
 */
export function fallbackOf(s) {
  const curve = curveOf(s);
  let at = [...EASES.out];
  let best = gap(at, curve);
  for (let step = 0.16; step >= 0.01; step /= 2) {
    for (let moved = true; moved;) {
      moved = false;
      for (let k = 0; k < 4; k++) {
        for (const dir of [-1, 1]) {
          const next = [...at];
          next[k] = Math.round((next[k] + dir * step) * 100) / 100;
          if ((k === 0 || k === 2) && (next[k] < 0 || next[k] > 1)) continue; // x stays in 0..1, as CSS asks
          const g = gap(next, curve);
          if (g < best - 1e-9) { best = g; at = next; moved = true; }
        }
      }
    }
  }
  return at;
}

/** motionCss is the block styles.css carries, from BEGIN to END. */
export function motionCss() {
  const springs = CSS_SPRINGS.map((name) => ({ name, ...springEasing(SPRINGS[name]), fallback: fallbackOf(SPRINGS[name]) }));
  const lines = [
    BEGIN,
    '/* The motion tokens: how long things take, and how they ease, for the',
    '   whole app (lib/objects/motion.js says what each is for). The same in',
    '   both schemes, and no material, so neither in the dark block nor in',
    '   objects.css. A spring is its curve and its own time, and the two go',
    '   together: --spring-snap over --t-spring-snap is the snap spring; over',
    '   any other time it is some other spring. */',
    ':root {',
    ...Object.entries(T).map(([k, v]) => `  --t-${k}: ${v}ms;`),
    ...Object.entries(EASES).map(([k, v]) => `  --ease-${k}: ${cubic(v)};`),
    ...springs.map((s) => `  --t-spring-${s.name}: ${s.duration}ms;`),
    ...springs.map((s) => `  --spring-${s.name}: ${s.easing};`),
    '}',
    '/* Without linear() (Safari before 17.2, Chrome before 113), the nearest',
    '   cubic-bézier: the same time, without the spring\'s own tail. */',
    '@supports not (transition-timing-function: linear(0, 1)) {',
    '  :root {',
    ...springs.map((s) => `    --spring-${s.name}: ${cubic(s.fallback)};`),
    '  }',
    '}',
    '/* Less motion, in one place: nothing travels, so every time a thing',
    '   travels in is 0. A fade (--t-touch, --t-exit) still says what changed. */',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...TRAVEL.map((k) => `    --t-${k}: 0ms;`),
    ...springs.map((s) => `    --t-spring-${s.name}: 0ms;`),
    '  }',
    '}',
    END,
  ];
  return lines.join('\n');
}
